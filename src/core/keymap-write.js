// Generate ZMK .keymap text from the editor model. When the model came from an
// imported file, only the keymap and combos nodes are regenerated.
import { parseDts, findNodes, hasCompatible } from '../dts/parse.js';
import { requiredIncludes, addIncludes } from './includes.js';
import { diagramComment } from './diagram.js';
import { behaviorEdits, containerLines } from './behaviors-write.js';

const IND = '    ';

export function sanitizeId(name, prefix) {
  let id = String(name ?? '')
    .toLowerCase()
    .replace(/[^a-z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '');
  if (!id) return prefix;
  return /^[a-z]/.test(id) ? id : `${prefix}_${id}`;
}

function uniqueIds(entries, prefix) {
  const taken = new Set(entries.map((e) => e.id).filter(Boolean));
  return entries.map((e) => {
    if (e.id) return e.id;
    const base = sanitizeId(e.name, prefix);
    let id = base;
    for (let n = 2; taken.has(id); n++) id = `${base}_${n}`;
    taken.add(id);
    return id;
  });
}

export const layerIds = (layers) => uniqueIds(layers, 'layer');

export function formatRows(bindings, rows) {
  const chunks = [];
  let i = 0;
  for (const n of rows) {
    if (i >= bindings.length) break;
    chunks.push(bindings.slice(i, i + n));
    i += n;
  }
  if (i < bindings.length) chunks.push(bindings.slice(i));
  const widths = [];
  for (const row of chunks) row.forEach((b, c) => (widths[c] = Math.max(widths[c] ?? 0, b.length)));
  return chunks.map((row) => row.map((b, c) => (c < row.length - 1 ? b.padEnd(widths[c]) : b)).join('  '));
}

const quote = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

function padBindings(bindings, keyCount, filler) {
  const out = [...bindings];
  while (out.length < keyCount) out.push(filler);
  return out;
}

function layerLines(layer, id, idx, opts, layers) {
  const bindings = padBindings(layer.bindings, opts.keyCount ?? 0, idx === 0 ? '&none' : '&trans');
  const diagram = opts.diagrams ? diagramComment({ ...layer, bindings }, layers, opts.keys, opts.rows) : [];
  return [
    ...diagram,
    `${id} {`,
    `${IND}display-name = ${quote(layer.name)};`,
    `${IND}bindings = <`,
    ...formatRows(bindings, opts.rows ?? []).map((r) => IND + IND + r),
    `${IND}>;`,
    ...(layer.extra ?? []).map((e) => IND + e),
    '};',
  ];
}

export function keymapLines(keymap, opts = {}, header = 'keymap') {
  const ids = layerIds(keymap.layers);
  const body = keymap.layers.flatMap((layer, idx) => ['', ...layerLines(layer, ids[idx], idx, opts, keymap.layers).map((l) => IND + l)]);
  return [`${header} {`, `${IND}compatible = "zmk,keymap";`, ...body, '};'];
}

function comboLines(combo, id) {
  return [
    `${id} {`,
    ...(combo.timeout != null ? [`${IND}timeout-ms = <${combo.timeout}>;`] : []),
    `${IND}key-positions = <${combo.keyPositions.join(' ')}>;`,
    `${IND}bindings = <${combo.binding}>;`,
    ...(combo.layers?.length ? [`${IND}layers = <${combo.layers.join(' ')}>;`] : []),
    ...(combo.requirePriorIdle != null ? [`${IND}require-prior-idle-ms = <${combo.requirePriorIdle}>;`] : []),
    ...(combo.slowRelease ? [`${IND}slow-release;`] : []),
    ...(combo.extra ?? []).map((e) => IND + e),
    '};',
  ];
}

export function combosLines(combos, header = 'combos') {
  const ids = uniqueIds(combos.map((c) => ({ name: c.name })), 'combo');
  const body = combos.flatMap((c, i) => ['', ...comboLines(c, ids[i]).map((l) => IND + l)]);
  return [`${header} {`, `${IND}compatible = "zmk,combos";`, ...body, '};'];
}

const indentLines = (lines, ind) => lines.map((l, i) => (i === 0 || !l ? l : ind + l)).join('\n');

function indentOf(text, pos) {
  const lineStart = text.lastIndexOf('\n', pos - 1) + 1;
  return text.slice(lineStart, pos).match(/^[ \t]*/)[0];
}

const nodeHeader = (node) => node.labels.map((l) => `${l}: `).join('') + node.name;

export function allBindings(keymap) {
  return [
    ...keymap.layers.flatMap((l) => l.bindings),
    ...keymap.combos.map((c) => c.binding),
    ...(keymap.behaviors ?? []).flatMap((b) => b.bindings),
  ];
}

function newContainers(behaviors) {
  return ['behaviors', 'macros']
    .map((name) => [name, behaviors.filter((b) => (b.kind === 'macro') === (name === 'macros'))])
    .filter(([, items]) => items.length)
    .map(([name, items]) => containerLines(name, items));
}

function generate(keymap, opts) {
  const includes = requiredIncludes(allBindings(keymap)).map((inc) => `#include <${inc}>`);
  const nodes = newContainers(keymap.behaviors ?? []).map((lines) => indentLines(lines, IND));
  if (keymap.combos.length) nodes.push(indentLines(combosLines(keymap.combos), IND));
  nodes.push(indentLines(keymapLines(keymap, opts), IND));
  const text = [
    '/*',
    ' * Generated by ZMK Keymap Editor',
    ' */',
    '',
    ...includes,
    '',
    '/ {',
    nodes.map((n) => IND + n).join('\n\n'),
    '};',
    '',
  ].join('\n');
  return { text, addedIncludes: [] };
}

function splice(keymap, opts) {
  const text = keymap.source;
  const root = parseDts(text);
  const kmNode = findNodes(root, (n) => hasCompatible(n, 'zmk,keymap'))[0];
  if (!kmNode) return generate(keymap, opts);
  const comboNode = findNodes(root, (n) => hasCompatible(n, 'zmk,combos'))[0];
  const kmInd = indentOf(text, kmNode.start);
  let kmText = indentLines(keymapLines(keymap, opts, nodeHeader(kmNode)), kmInd);
  const { edits, prefix } = behaviorEdits(text, root, keymap.behaviors ?? []);
  if (comboNode) {
    const ind = indentOf(text, comboNode.start);
    edits.push({ start: comboNode.start, end: comboNode.end, text: indentLines(combosLines(keymap.combos, nodeHeader(comboNode)), ind) });
  } else if (keymap.combos.length) {
    kmText = indentLines(combosLines(keymap.combos), kmInd) + '\n\n' + kmInd + kmText;
  }
  for (const lines of prefix.reverse()) kmText = indentLines(lines, kmInd) + '\n\n' + kmInd + kmText;
  edits.push({ start: kmNode.start, end: kmNode.end, text: kmText });
  edits.sort((a, b) => b.start - a.start);
  let out = text;
  for (const e of edits) out = out.slice(0, e.start) + e.text + out.slice(e.end);
  const { text: withIncludes, added } = addIncludes(out, requiredIncludes(allBindings(keymap)));
  return { text: withIncludes, addedIncludes: added };
}

// opts: { rows: [bindings per row], keyCount: pad layers to this many bindings,
//         diagrams: add layer diagram comments, keys: physical keys for the diagrams }
// Returns { text, addedIncludes }.
export function writeKeymapDetailed(keymap, opts = {}) {
  const o = { ...opts, rows: opts.rows ?? keymap.rowHints ?? [], keyCount: opts.keyCount ?? 0 };
  return keymap.source ? splice(keymap, o) : generate(keymap, o);
}

export function writeKeymap(keymap, opts = {}) {
  return writeKeymapDetailed(keymap, opts).text;
}
